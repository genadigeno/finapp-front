// Adapted from finapp-admin-panel/scripts/contract-generate.mjs (ADR-F08: copied by reading, not shared).
// Generates the TypeScript types for the pinned contract with openapi-typescript (types only - no
// runtime code is generated, ADR-F03). Output: src/generated/finapp-api.ts, or the path given.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import { CONTRACT_FILE, GENERATED_FILE, SOURCE_FILE } from './lib/contract.mjs';

const out = process.argv[2] ?? GENERATED_FILE;
const schema = JSON.parse(readFileSync(CONTRACT_FILE, 'utf8'));
const { commit } = JSON.parse(readFileSync(SOURCE_FILE, 'utf8'));

const ast = await openapiTS(schema, {
  // Every documented property is present in a response unless the contract says otherwise;
  // missing fields stay optional exactly as the contract declares them.
  alphabetize: true,
  exportType: true,
});
const header =
  `// GENERATED by scripts/contract-generate.mjs from contract/openapi.json\n` +
  `// (finapp ${commit}). Do not edit: change the backend contract and regenerate.\n\n`;
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, header + astToString(ast));
console.log(`Generated ${out}.`);
